export type LanguageKey = keyof typeof dictionary;

export function t(key: keyof (typeof dictionary)['es']): string {
  const { language } = appState.get();
  return dictionary[language][key] || key;
}

export function setLanguage(lang: LanguageKey): void {
  appState.set({ language: lang });
}

export function applyTranslations(root: HTMLElement): void {
  const { language } = appState.get();
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n') as keyof (typeof dictionary)['es'];
    if (!key) return;
    el.textContent = dictionary[language][key];
  });

  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder') as keyof (typeof dictionary)['es'];
    if (!key) return;
    if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement) {
      el.placeholder = dictionary[language][key];
    }
  });
}
